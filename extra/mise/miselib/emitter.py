_PREC = {"or": 1, "and": 2, "==": 3, "!=": 3, "<": 3, "<=": 3, ">": 3, ">=": 3,
         "..": 4, "+": 5, "-": 5, "*": 6, "/": 6, "%": 6}


def _parens_on_right(op: str, right: str) -> bool:
    """A right operand needs its own parentheses: Lua is left-associative, so an
    equal precedence there would be regrouped (`a - (b - c)` is not `a - b - c`).
    `..` is the exception — Lua groups it to the right, and the value is the same."""
    parent, child = _PREC[op], _PREC[right]
    return child < parent or (child == parent and op != "..")


def lua_str(s: str) -> str:
    if "\n" in s or "\\" in s or ('"' in s and "'" in s):
        eq = ""
        while f"]{eq}]" in s or s.endswith("]"):
            eq += "="
        lead = "\n" if s.startswith("\n") else ""
        return f"[{eq}[{lead}{s}]{eq}]"
    return f"'{s}'" if '"' in s else f'"{s}"'


_VERB_ORDER = {"verb": 0, "extend": 1, "remove": 2}


def _class_has_body(ent: EntityDecl) -> bool:
    """Does the class carry anything the engine has to run or store?"""
    return bool(ent.words or ent.traits or ent.handlers
                or any(p.value is not None for p in ent.props))


def _merged_classes(items: List[Any], ctx: Context) -> Dict[str, EntityDecl]:
    """One declaration per class: a class may be written in pieces.

    The field declarations are already merged by the checker (they live on the
    first piece); the parent, words, traits and handlers are collected here.
    """
    merged: Dict[str, EntityDecl] = {}
    for ent in items:
        if not isinstance(ent, EntityDecl) or ent.kind != "class" or not ent.name:
            continue
        decl = merged.get(ent.name)
        if decl is None:
            first = ctx.class_decls.get(ent.name, ent)
            merged[ent.name] = replace(first, words=list(ent.words), traits=list(ent.traits),
                                       handlers=list(ent.handlers), props=list(first.props))
            continue
        decl.parent = decl.parent or ent.parent
        decl.ctor = decl.ctor or ent.ctor
        decl.words = decl.words or list(ent.words)
        decl.traits += [t for t in ent.traits if t not in decl.traits]
        decl.handlers += [h for h in ent.handlers if h not in decl.handlers]
    return merged


def _class_names_in_use(items: List[Any]) -> Set[str]:
    """Names an emitted `Class` global is needed for: a parent, an instance."""
    used: Set[str] = set()
    for ent in items:
        if not isinstance(ent, EntityDecl):
            continue
        if ent.kind == "class":
            used.update([ent.parent] if ent.parent else [])
        elif ent.kind != "impl" and ent.name is not None:
            used.add(ent.kind)
    return used


def _class_plan(items: List[Any], ctx: Context) -> List[EntityDecl]:
    """The `Class` chunks to emit, a parent before its child.

    A class is skipped when the engine owns it (`class story(room) = cutscene`)
    or when it only spells out field types and nothing refers to it — such a
    declaration exists for the checker, there is nothing to build.
    """
    merged = _merged_classes(items, ctx)
    in_use = _class_names_in_use(items)
    order: List[EntityDecl] = []
    placed: Set[str] = set()

    def place(start: EntityDecl):
        chain = [start]
        while chain[-1].parent in merged and merged[chain[-1].parent] not in chain:
            chain.append(merged[chain[-1].parent])
        for c in reversed(chain):
            if c.name not in placed and c.name not in ctx.ctors \
                    and (_class_has_body(c) or c.name in in_use):
                placed.add(c.name)
                order.append(c)

    for decl in merged.values():
        place(decl)
    return order


def _ind(text: str, n: int = 2) -> str:
    pad = " " * n
    return "\n".join(pad + l if l.strip() else "" for l in lua_lines(text))


class Emitter:
    def __init__(self, prog: Program, ctx: Context):
        self.prog, self.ctx = prog, ctx

    def emit(self) -> str:
        chunks = ["-- generated by mise.py; do not edit"]
        hdr = [f"--${k.capitalize()}:{v}$" for k, v in self.prog.meta]
        hdr.append('require "fmt"')
        hdr.extend(f"fmt.{f} = true" for f in self.prog.fmt)
        hdr.extend(f'require "{r}"' for r in self.prog.requires)
        hdr.append(f'require "parser/mp-{self.prog.lang}"')
        chunks.append("\n".join(hdr))

        rendered: List[Tuple[FnDecl, str, str]] = []
        for it in self.prog.items:
            if isinstance(it, FnDecl) and not it.is_extern:
                if it.name in self.ctx.entries:
                    continue
                if isinstance(it.body, str) and not it.body.strip().startswith(("local ", "return ")) and "\n" not in it.body and it.name not in self.ctx.used_refs:
                    continue
                rendered.append((it, *self._fn_parts(it)))

        # One local table, not one local per function: a chunk may hold only 200
        # locals, and a function of the table is visible before it is assigned,
        # so mutual recursion needs no forward declarations either.
        if rendered:
            chunks.append("local fn = {}")
        for fn, prms, body in rendered:
            head = f"fn.{fn.name} = function({prms})"
            chunks.append(f"{head}\n{body}\nend" if body.strip() else f"{head}\nend")

        for it in self._emission_order():
            if isinstance(it, FnDecl) and not it.is_extern and it.name in self.ctx.entries:
                prms = ", ".join(pn for pn, _pt in it.params)
                body = _ind(self._stmts(it.body), 2) if isinstance(it.body, list) else _ind(it.body, 2)
                chunks.append(f"function {it.name}({prms})\n{body}\nend" if body.strip() else f"function {it.name}({prms})\nend")
            elif isinstance(it, LuaDecl):
                chunks.append(it.code)
            elif isinstance(it, VarDecl):
                chunks.append("\n".join(f"{it.kind} '{vn}' ({self._prop_scalar(ve)})" for vn, _vt, ve, _l in it.items))
            elif isinstance(it, EntityDecl):
                s = self._emit_entity(it)
                if s:
                    chunks.append(s)
            elif isinstance(it, VerbDecl):
                chunks.append(self._emit_verb(it))
            elif isinstance(it, TalkDecl):
                chunks.append(self._emit_talk(it))

        return "\n\n".join(c for c in chunks if c.strip()) + "\n"

    def _emission_order(self) -> List[Any]:
        """The chunks that run at load time, in an order that does not depend on
        the source order of the declarations.

        The engine executes the file top to bottom, so a parent class has to be
        built before its child, an object before an `impl` that writes into it,
        and a verb before `extend`/`remove` of that verb. Functions are emitted
        before all of this (see `emit`), and object fields hold names, not
        references, so the rest keeps the source order.
        """
        items = self.prog.items
        entries = [it for it in items if isinstance(it, FnDecl) and it.name in self.ctx.entries]
        values = [it for it in items
                  if isinstance(it, (LuaDecl, VarDecl, TalkDecl))
                  or (isinstance(it, EntityDecl) and it.kind not in ("class", "impl"))]
        verbs = sorted((it for it in items if isinstance(it, VerbDecl)),
                       key=lambda v: _VERB_ORDER[v.mode])
        impls = [it for it in items if isinstance(it, EntityDecl) and it.kind == "impl"]
        return entries + _class_plan(items, self.ctx) + values + verbs + impls

    def _fn_parts(self, fn: FnDecl) -> Tuple[str, str]:
        prms = ", ".join([pn for pn, _pt in fn.params] + (["..."] if fn.variadic else []))
        if isinstance(fn.body, str):
            code = fn.body.strip()
            if not code.startswith(("return ", "local ")) and "\n" not in code:
                code = "return " + code
            body = _ind(code, 2)
        else:
            body = _ind(self._stmts(fn.body), 2)
        return prms, body

    def _emit_entity(self, ent: EntityDecl, ind: int = 0) -> str:
        if ent.kind == "class":
            if ent.name in self.ctx.ctors:
                return ""               # `class story(room) = cutscene`: the engine owns it
            lines, tails = self._obj_parts(ent, is_class=True, ind=0)
            inner = "\n".join(lines)
            if ent.parent and ent.parent != self.ctx.root_class:
                head = f"{ent.name} = Class({{\n{inner}\n}}, {ent.parent})" if inner else f"{ent.name} = Class({{}}, {ent.parent})"
            else:
                head = f"{ent.name} = Class {{\n{inner}\n}}" if inner else f"{ent.name} = Class {{}}"
            return head + "".join(tails)

        if ent.kind == "impl":
            return self._emit_impl(ent)

        ctor = self.ctx.ctors.get(ent.kind, ent.kind)
        lines, tails = self._obj_parts(ent, is_class=False, ind=ind)
        pad = " " * ind
        inner = ("\n" + "\n".join(lines) + f"\n{pad}") if lines else f"\n{pad}"
        return f"{pad}{ctor} {{{inner}}}" + "".join(tails)

    def _obj_parts(self, ent: EntityDecl, is_class: bool, ind: int) -> Tuple[List[str], List[str]]:
        lines, tails = [], []
        fpad = " " * (ind + 2)
        if ent.words:
            w = lua_str("|".join(ent.words))
            lines.append(f"{fpad}word = -{w};" if is_class else f"{fpad}-{w};")
        if not is_class and ent.name:
            lines.append(f"{fpad}nam = {lua_str(ent.name)};")
        attrs = [tr for tr in ent.traits if tr not in self.ctx.classes]
        if ent.locations:
            v = f"'{ent.locations[0]}'" if len(ent.locations) == 1 else "{ " + ", ".join(f'"{l}"' for l in ent.locations) + " }"
            lines.append(f"{fpad}found_in = {v};")
        for p in ent.props:
            if p.value is None:
                continue
            call = self._method_call(p)
            if call is not None:
                if call:
                    tails.append(call)
                continue
            lines.append(f"{fpad}{p.name} = {self._prop_val(p, ind + 2)};")
        for h in ent.handlers:
            k, fn = self._handler_pair(h, ind + 2)
            lines.append(f"{fpad}{k} = {fn};")
        if ent.children:
            objs = [self._emit_entity(c, ind + 4) + ";" for c in ent.children]
            lines.append(f"{fpad}obj = {{\n" + "\n".join(objs) + f"\n{fpad}}};")
        if attrs:
            tails.insert(0, f":attr '{','.join(attrs)}'")
        return lines, tails

    def _method_call(self, p: Prop) -> Optional[str]:
        """The engine method call a field turns into, or None for a plain field."""
        spec = p.emit
        if spec is None:
            return None
        mname, form, other, v = spec.method, spec.form, spec.other, p.value
        if form == "none":
            if not isinstance(v, Lit) or v.kind != "bool":
                return ""
            return f":{mname}()" if v.val else (f":{other}()" if other else "")
        if form == "table":
            return f":{mname} {v.val}" if isinstance(v, Lit) and v.kind == "table" else ""
        items = v.items if isinstance(v, ListLit) else [v]
        if form == "join":                  # `:attr 'a,b'` — one comma-joined string
            parts = [it.name if isinstance(it, Sym) else self._expr(it).strip("'\"") for it in items]
            return f":{mname} '{','.join(parts)}'"
        if form == "list":                  # `:with{ 'a', 'b' }` — names, resolved by the engine
            parts = [self._prop_scalar(it) for it in items]
            return f":{mname}{{ {', '.join(parts)} }}" if parts else ""
        args = [self._expr(it) for it in items]
        return f":{mname}({', '.join(args)})" if args else ""

    def _if_chain(self, branches, else_body, ind: int = 0) -> str:
        """`if`/`elseif` chain; a `:=` branch binds its names in a `do` block."""
        pad = " " * ind
        cond, body, _l = branches[0]
        if isinstance(cond, Bind):
            b = _ind(self._stmts(body), ind + 4)
            lines = [f"{pad}do",
                     f"{pad}  local {', '.join(cond.names)} = {self._expr(cond.value)}",
                     f"{pad}  if {' and '.join(cond.names)} then"]
            if b.strip():
                lines.append(b)
            tail = self._if_else(branches[1:], else_body, ind + 2)
            if tail:
                lines.append(tail)
            lines += [f"{pad}  end", f"{pad}end"]
            return "\n".join(lines)
        b = _ind(self._stmts(body), ind + 2)
        lines = [f"{pad}if {self._expr(cond)} then"]
        if b.strip():
            lines.append(b)
        tail = self._if_else(branches[1:], else_body, ind)
        if tail:
            lines.append(tail)
        lines.append(f"{pad}end")
        return "\n".join(lines)

    def _if_else(self, branches, else_body, ind: int) -> str:
        """The rest of a chain: `elseif` arms, or `else` with the remaining chain."""
        pad = " " * ind
        if not branches:
            if else_body is None:
                return ""
            eb = _ind(self._stmts(else_body), ind + 2)
            return f"{pad}else" + (("\n" + eb) if eb.strip() else "")
        cond, body, _l = branches[0]
        if isinstance(cond, Bind):
            return f"{pad}else\n" + self._if_chain(branches, else_body, ind + 2)
        b = _ind(self._stmts(body), ind + 2)
        head = f"{pad}elseif {self._expr(cond)} then"
        if b.strip():
            head += "\n" + b
        tail = self._if_else(branches[1:], else_body, ind)
        if tail:
            head += "\n" + tail
        return head

    def _pure(self, e: Expr) -> bool:
        """Can this expression be evaluated twice without side effects?"""
        if isinstance(e, Lit):
            return True
        if isinstance(e, Sym):
            return e.rk not in ("fn0",)          # a bare fn name is a call
        if isinstance(e, FieldAccess):
            return self._pure(e.obj)
        if isinstance(e, IndexAccess):
            return self._pure(e.obj) and self._pure(e.index)
        if isinstance(e, InterpStr):
            return all(self._pure(x) if isinstance(x, Expr) else True for x in e.parts)
        if isinstance(e, UnaryOp):
            return self._pure(e.operand)
        if isinstance(e, BinOp):
            return self._pure(e.left) and self._pure(e.right)
        return False

    def _in_op(self, e: InOp) -> str:
        """`x in a, b` — compare once (a call subject is bound to a parameter)."""
        subj = self._expr(e.subject)
        chks = [f"{'c' if not self._pure(e.subject) else subj} == {self._expr(a)}"
                for a in e.alts]
        expr = " or ".join(chks) if chks else "false"
        if self._pure(e.subject):
            return f"({expr})"
        return f"(function(c) return {expr} end)({subj})"

    def _prop_val(self, p: Prop, ind: int = 0) -> str:
        v, pad = p.value, " " * ind
        if isinstance(v, FnRef):
            return self._fnref(v.name)
        if isinstance(v, Lit):
            if v.kind in ("table", "raw"):     # `{ ... }` verbatim, a `` `lua expression` ``
                return v.val
            if v.kind == "lua":                # a `lua` block: an opaque body
                prms = self._prop_prms(p)
                return f"function({prms})\n{_ind(v.val, ind + 2)}\n{pad}end"
        if isinstance(v, list):
            prms = self._prop_prms(p)
            b = _ind(self._stmts(v), ind + 2)
            return f"function({prms})\n{b}\n{pad}end" if b.strip() else f"function({prms})\n{pad}end"
        if isinstance(v, Lambda) and isinstance(v.body, list):
            prms = ", ".join(pn for pn, _t in v.params)
            b = _ind(self._stmts(v.body), ind + 2)
            return f"function({prms})\n{b}\n{pad}end" if b.strip() else f"function({prms})\n{pad}end"
        if isinstance(v, ListLit):
            is_r = p.is_ref
            items = [f'"{it.name}"' if (is_r and isinstance(it, Sym) and it.name in self.ctx.objects)
                     else (self._prop_scalar(it) if is_r else self._expr(it))
                     for it in v.items]
            if is_r and len(items) == 1 and isinstance(v.items[0], Sym) and v.items[0].name in self.ctx.objects:
                return f"'{v.items[0].name}'"
            if len(items) > 1:                      # a field list: one item per line
                body = "".join(f"{pad}  {it},\n" for it in items)
                return "{\n" + body + pad + "}"
            return "{ " + ", ".join(items) + " }"
        if isinstance(v, Expr):
            return self._prop_scalar(v)
        return "nil"

    def _prop_prms(self, p: Prop) -> str:
        """Parameters of a prop body, resolved by the checker."""
        return ", ".join(p.params) if p.params else "s"

    def _prop_scalar(self, e: Expr) -> str:
        if isinstance(e, Sym):
            if e.name in self.ctx.objects:
                return f"'{e.name}'"
            if e.name in self.ctx.event_names or e.rk in ("enum", "event"):
                return lua_str(e.name)
            if e.rk == "global_ref":
                return e.name
        return self._expr(e)

    def _handler_pair(self, h: Handler, ind: int = 0) -> Tuple[str, str]:
        pad, pfx = " " * ind, ("" if h.phase == "on" else h.phase + "_")
        joined = ",".join(h.events)
        key = f'["{pfx}{joined}"]' if len(h.events) > 1 else f"{pfx}{joined}"
        is_any = any(ev in ("Any", "Default") for ev in h.events)
        prms = ", ".join(h.params) if h.params is not None else ("s, ev, w, wh" if is_any else "s, w, wh")
        if h.body == "pass":
            return key, f"function({prms}) return false end"
        if h.body == "stop":
            return key, f"function({prms}) return end"
        if isinstance(h.body, FnRef):
            return key, self._fnref(h.body.name)
        if isinstance(h.body, Lit) and h.body.kind == "str":
            return key, lua_str(h.body.val)
        if isinstance(h.body, Lit) and h.body.kind == "lua":
            return key, f"function({prms})\n{_ind(h.body.val, ind + 2)}\n{pad}end"
        if isinstance(h.body, InterpStr):
            return key, f"function({prms})\n{_ind(self._p_call(h.body, 'p'), ind + 2)}\n{pad}end"
        if isinstance(h.body, list):
            b = _ind(self._stmts(h.body), ind + 2)
            return key, f"function({prms})\n{b}\n{pad}end" if b.strip() else f"function({prms})\n{pad}end"
        return key, "nil"

    def _emit_impl(self, ent: EntityDecl) -> str:
        t = ent.name or "game"
        ref = t if (t in self.ctx.classes or t in ("mp", "pl")) else f"_'{t}'"
        lines = []
        if ent.words:
            lines.append(f"{ref}.word = -{lua_str('|'.join(ent.words))}")
        for p in ent.props:
            call = self._method_call(p)
            if call is not None:
                if call:
                    lines.append(f"{ref}{call}")
                continue
            # `-"…"` is the engine's word marker (`__unm` on a string is identity),
            # so an assignment keeps it: `pl.word = -"ты"` as mp-ru.lua does
            lines.append(f"{ref}.{p.name} = {self._prop_val(p)};")
        for h in ent.handlers:
            k, fn = self._handler_pair(h)
            if k.startswith("["):
                lines.append(f"{ref}{k} = {fn};")
                if t in self.ctx.classes:
                    lines.append(f'std.fn_aliases({ref}, "{k[2:-2]}")')
            else:
                lines.append(f"{ref}.{k} = {fn};")
        return "\n".join(lines)

    def _emit_verb(self, v: VerbDecl) -> str:
        if v.mode == "remove":
            return f"VerbRemove '{v.name}'"
        its = []
        tag = (f"#{v.name}" if v.tag is None else v.tag) if v.mode == "verb" else v.name
        if tag:
            its.append(lua_str(tag))
        if v.words:
            its.append(lua_str("|".join(v.words)))
        its.extend(lua_str(p) for p in v.patterns)
        if v.prio is not None:
            its.append(f"prio = {v.prio}")
        if v.hint is not None:
            _, fn = self._handler_pair(Handler(phase="on", events=["hint"], params=["s"], body=v.hint))
            its.append(f"hint = {fn}")
        call = "Verb" if v.mode == "verb" else ("VerbExtendWord" if v.words else "VerbExtend")
        return f"{call}({{ {', '.join(its)} }}, _'{v.target}')" if v.target else f"{call} {{ {', '.join(its)} }}"

    def _emit_talk(self, td: TalkDecl) -> str:
        lines = [f"dlg {{\n  nam = '{td.name}';"]
        lines.extend(f"  {p.name} = {self._prop_val(p)};" for p in td.props)
        phrs = ([self._talk_val(td.intro, 4)] if td.intro is not None else []) + [self._talk_choice(c, 4) for c in td.choices]
        lines.append("  phr = {\n" + "\n".join(phrs) + "\n  };")
        if td.labels:
            lbls = []
            for lname, lsay, lcs in td.labels:
                tag = lname if lname.startswith("#") else f"#{lname}"
                its = ["    {", f"      '{tag}';"]
                if lsay is not None:
                    its.append(self._talk_val(lsay, 6))
                its.extend(self._talk_choice(c, 6) for c in lcs)
                its.append("    };")
                lbls.append("\n".join(its))
            lines.append("  obj = {\n" + "\n".join(lbls) + "\n  };")
        lines.append("}")
        return "\n".join(lines)

    def _talk_val(self, v: Any, ind: int) -> str:
        pad = " " * ind
        if isinstance(v, FnRef):
            return f"{pad}{self._fnref(v.name)};"
        if isinstance(v, Lit) and v.kind == "str":
            return f"{pad}{lua_str(v.val)};"
        if isinstance(v, list):
            return f"{pad}function(s)\n{_ind(self._stmts(v), ind + 2)}\n{pad}end;"
        return f"{pad}{self._expr(v)};"

    def _talk_choice(self, c: TalkChoice, ind: int) -> str:
        pad, ipad = " " * ind, " " * (ind + 2)
        its = [f"{pad}{{"]
        if c.ask is not None:
            its.append(self._talk_val(c.ask, ind + 2))
        has_do = bool(c.do)
        if c.reply is not None and not has_do:
            its.append(self._talk_val(c.reply, ind + 2))
        elif c.reply is not None or has_do:
            if c.reply is None and isinstance(c.do, FnRef):
                its.append(f"{ipad}{self._fnref(c.do.name)};")
            else:
                act = []
                if isinstance(c.reply, (Lit, InterpStr)):
                    act.append(self._p_call(c.reply, "p"))
                elif isinstance(c.reply, FnRef):
                    act.append(f"p({self._fnref(c.reply.name)}(s))")
                elif isinstance(c.reply, list):
                    act.append(self._stmts(c.reply))
                if isinstance(c.do, FnRef):
                    act.append(f"{self._fnref(c.do.name)}(s)")
                elif isinstance(c.do, list):
                    act.append(self._stmts(c.do))
                its.append(f"{ipad}function(s)\n{_ind(chr(10).join(act), ind + 4)}\n{ipad}end;")
        its.extend(self._talk_choice(sub, ind + 2) for sub in c.children)
        if c.onempty is not None:
            its.append(f"{ipad}onempty = {self._talk_val(c.onempty, 0).strip().rstrip(';')};")
        for f in ("always", "hidden", "only"):
            if f in c.flags:
                its.append(f"{ipad}{f} = true;")
        if c.next_label:
            its.append(f"{ipad}next = '{c.next_label if c.next_label.startswith('#') else '#' + c.next_label}';")
        if c.cond is not None:
            if isinstance(c.cond, FnRef):
                its.append(f"{ipad}cond = {self._fnref(c.cond.name)};")
            elif isinstance(c.cond, list):
                its.append(f"{ipad}cond = function(s)\n{_ind(self._stmts(c.cond), ind + 4)}\n{ipad}end;")
            else:
                its.append(f"{ipad}cond = function(s) return {self._expr(c.cond)} end;")
        its.append(f"{pad}}};")
        return "\n".join(its)

    # --- Statements & Expressions ---

    def _stmts(self, stmts: List[Stmt]) -> str:
        return "\n".join(self._stmt(s) for s in stmts)

    def _stmt(self, s: Stmt) -> str:
        if isinstance(s, SayStmt):
            return self._p_call(s.expr, s.mode)
        if isinstance(s, ReturnStmt):
            if s.kind == "stop":
                return "return"
            if s.kind == "pass":
                return "return false"
            if s.kind == "break":
                return "break"
            return ("return " + ", ".join(self._expr(v) for v in s.values)) if s.values else "return"
        if isinstance(s, LocalStmt):
            ns = ", ".join(n for n, _t in s.names)
            return f"local {ns} = {', '.join(self._expr(v) for v in s.values)}" if s.values else f"local {ns}"
        if isinstance(s, AssignStmt):
            lhs = f"{self._expr(s.target.obj)}.{s.target.field}" if isinstance(s.target, FieldAccess) else self._expr(s.target, as_lhs=True)
            rhs = ", ".join(self._expr(v) for v in s.values)
            return f"{lhs} = {rhs}" if s.op == "=" else f"{lhs} = {lhs} {s.op[0]} ({rhs})"
        if isinstance(s, CallStmt):
            return self._call(s.call, as_stmt=True)
        if isinstance(s, IfStmt):
            return self._if_chain(s.branches, s.else_body)
        if isinstance(s, MatchStmt):
            # the subject is evaluated once; arms are `or`-chains (like `in`)
            subj = self._expr(s.subject)
            arms, else_b = [], None
            for pats, guard, body, _l in s.arms:
                if len(pats) == 1 and isinstance(pats[0], Sym) and pats[0].name == "_" and not guard:
                    else_b = body
                    break
                chks = [f"{MATCH_TMP} == {self._expr(p)}" for p in pats
                        if not (isinstance(p, Sym) and p.name == "_")]
                cstr = " or ".join(chks)
                if guard:
                    gstr = self._expr(guard)
                    cstr = f"({cstr}) and {gstr}" if len(chks) > 1 \
                        else (f"{cstr} and {gstr}" if cstr else gstr)
                arms.append((cstr or "true", body))
            if not arms:
                eb = self._stmts(else_b) if else_b else ""
                inner = f"local {MATCH_TMP} = {subj}" + (f"\n{eb}" if eb.strip() else "")
                return "do\n" + _ind(inner, 2) + "\nend"
            parts = []
            for i, (cstr, body) in enumerate(arms):
                kw = "if" if i == 0 else "elseif"
                b = _ind(self._stmts(body), 2)
                parts.append(f"{kw} {cstr} then\n{b}" if b.strip() else f"{kw} {cstr} then")
            if else_b is not None:
                eb = _ind(self._stmts(else_b), 2)
                parts.append(f"else\n{eb}" if eb.strip() else "else")
            parts.append("end")
            return "do\n" + _ind(f"local {MATCH_TMP} = {subj}\n" + "\n".join(parts), 2) + "\nend"
        if isinstance(s, ForNumStmt):
            hdr = f"{s.var} = {self._expr(s.start)}, {self._expr(s.stop)}" + (f", {self._expr(s.step)}" if s.step else "")
            b = _ind(self._stmts(s.body), 2)
            return f"for {hdr} do\n{b}\nend" if b.strip() else f"for {hdr} do\nend"
        if isinstance(s, ForInStmt):
            vs = ", ".join(n for n, _t in s.vars)
            it = self._expr(s.iter_expr)
            hdr = (f"_, {vs} in ipairs({it})" if len(s.vars) == 1 else f"{vs} in ipairs({it})") if s.is_of else f"{vs} in {it}"
            b = _ind(self._stmts(s.body), 2)
            return f"for {hdr} do\n{b}\nend" if b.strip() else f"for {hdr} do\nend"
        return ""

    def _p_call(self, e: Expr, fn: str = "p") -> str:
        if isinstance(e, Lit) and e.kind == "str":
            lit = lua_str(e.val)
            return f"{fn}({lit})" if lit.startswith("[") else f"{fn} {lit}"
        if isinstance(e, InterpStr):
            args = [lua_str(p) if isinstance(p, str) else self._expr(p) for p in e.parts]
            return f"{fn}({', '.join(args)})"
        return f"{fn}({self._expr(e)})"

    def _expr(self, e: Expr, as_lhs: bool = False) -> str:
        if isinstance(e, Lit):
            return ("true" if e.val else "false") if e.kind == "bool" else ("nil" if e.kind == "nil" else (lua_str(e.val) if e.kind == "str" else str(e.val)))
        if isinstance(e, InterpStr):
            return "(" + " .. ".join(lua_str(p) if isinstance(p, str) else f"tostring({self._expr(p)})" for p in e.parts) + ")"
        if isinstance(e, FnRef):
            return self._fnref(e.name)
        if isinstance(e, ListLit):
            return ("{ " + ", ".join(self._expr(it) for it in e.items) + " }") if e.items else "{}"
        if isinstance(e, Sym):
            n = e.name
            if as_lhs or e.rk == "var":
                return n
            if e.rk == "obj":
                return f"_'{n}'"
            if e.rk == "global_ref":
                return f"_({n})"
            if e.rk in ("event", "enum"):
                return lua_str(n)
            if e.rk == "fn0":
                return self._call(Call(line=e.line, func=n))
            if e.rk == "value":
                fn = self.ctx.fns.get(n)
                return self._expand(fn, [], False) if fn and isinstance(fn.body, str) else n
            return n
        if isinstance(e, FieldAccess):
            c = f"{self._expr(e.obj)}.{e.field}"
            return f"_({c})" if (e.is_ref and not as_lhs) else c
        if isinstance(e, IndexAccess):
            return f"{self._expr(e.obj)}[{self._expr(e.index)}]"
        if isinstance(e, UnaryOp):
            in_s = f"({self._expr(e.operand)})" if isinstance(e.operand, BinOp) else self._expr(e.operand)
            return f"not {in_s}" if e.op == "not" else f"-{in_s}"
        if isinstance(e, Lambda):
            prms = ", ".join(pn for pn, _t in e.params)
            if isinstance(e.body, list):
                b = _ind(self._stmts(e.body), 2)
                return f"function({prms})\n{b}\nend" if b.strip() else f"function({prms}) end"
            return f"function({prms}) return {self._expr(e.body)} end"
        if isinstance(e, InOp):
            return self._in_op(e)
        if isinstance(e, BinOp):
            op = "~=" if e.op == "!=" else e.op
            ls, rs = self._expr(e.left), self._expr(e.right)
            if isinstance(e.left, BinOp) and _PREC[e.left.op] < _PREC[e.op]:
                ls = f"({ls})"
            if isinstance(e.right, BinOp) and _parens_on_right(e.op, e.right.op):
                rs = f"({rs})"
            return f"{ls} {op} {rs}"
        if isinstance(e, Call):
            return self._call(e)
        return "nil"

    def _fnref(self, name: str) -> str:
        return f"fn.{name}"

    def _call(self, c: Call, as_stmt: bool = False) -> str:
        if not c.receiver and c.func in ("say", "append", "line"):
            fn = {"say": "p", "append": "pr", "line": "pn"}[c.func]
            if not c.args:
                return f"{fn}()"
            return self._p_call(c.args[0], fn) if len(c.args) == 1 else f"{fn}({', '.join(self._expr(a) for a in c.args)})"
        all_a = ([c.receiver] + c.args) if c.receiver else list(c.args)
        fn = self.ctx.fns.get(c.func)
        args = [self._expr(a) for a in all_a]
        if fn and isinstance(fn.body, str) and (fn.is_extern or (not fn.body.strip().startswith(("local ", "return ")) and "\n" not in fn.body)) and c.func not in self.ctx.used_refs:
            return self._expand(fn, args, as_stmt)
        return f"fn.{c.func}({', '.join(args)})" if c.func in self.ctx.fns else f"{c.func}({', '.join(args)})"

    def _expand(self, fn: FnDecl, args: List[str], as_stmt: bool) -> str:
        t = fn.body
        if "$" in t:
            return _fill_slots(t, args)
        for (pn, _pt), av in zip(fn.params, args):
            # a lambda keeps `\1`/`\g<…>` in the argument from being read as a group
            t = re.sub(rf"\b{re.escape(pn)}\b", lambda _m, av=av: av, t)
        if as_stmt or t.startswith("(") or _SIMPLE_EXPR.match(t.strip()):
            return t
        return f"({t})"


def _fill_slots(text: str, args: List[str]) -> str:
    """Fill the `$1`, `$*` and `$2...` slots of an extern template in one pass.

    The slots are found from the right, so an inserted argument is never scanned
    again: a game string that happens to contain `$1` reaches the output as it
    is. An empty argument takes the comma that connected it (`g($1, $2...)` with
    one argument is `g(a)`, not `g(a, )`).
    """
    end = len(text)
    while True:
        at = text.rfind("$", 0, end)
        if at < 0:
            return text
        stop, value = _slot_at(text, at, args)
        if stop < 0:                       # a lone `$`: keep it, look further left
            end = at
            continue
        head, tail = text[:at], text[stop:]
        if not value:
            head = head.rstrip()
            head = head[:-1] if head.endswith(",") else head
            tail = tail.lstrip()
            tail = tail[1:] if tail.startswith(",") else tail
        text = head + value + tail
        end = at


def _slot_at(text: str, at: int, args: List[str]) -> Tuple[int, str]:
    """The value of the `$…` slot at `at` and the offset just past it.

    `-1` as the offset means "not a slot" (a bare `$`).
    """
    i = at + 1
    if text[i:i + 1] == "*":
        return i + 1, ", ".join(args)
    j = i
    while j < len(text) and text[j].isdigit():
        j += 1
    if j == i:
        return -1, ""
    idx = int(text[i:j]) - 1
    if text.startswith("...", j):
        return j + 3, (", ".join(args[idx:]) if idx >= 0 else "")
    return j, (args[idx] if 0 <= idx < len(args) else "")


_SIMPLE_EXPR = re.compile(r"[A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*(?:\([^()]*\))?")


def transpile(src: str, src_dir: str = "", src_name: str = "") -> str:
    prog = load_includes(parse_source(src, src_name), src_dir)
    return Emitter(prog, prescan(prog)).emit()
